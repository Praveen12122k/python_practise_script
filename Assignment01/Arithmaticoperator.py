#Problem: Take two integers from the user and perform the following operations:
num_one=int(input('Enter First Number: '))
num_two=int(input('Enter Second Number: '))

print(f'Addition  of Two Number: {num_one+num_two}')
print(f'Subtraction  of Two Number: {num_one-num_two}')
print(f'Multiplication  of Two Number: {num_one*num_two}')
print(f'Division  of Two Number: {num_one/num_two}')
print(f'F Division  of Two Number: {num_one//num_two}')
print(f'Modulus  of Two Number: {num_one%num_two}')
print(f'Exponent  of Two Number: {(num_one**num_two)}')